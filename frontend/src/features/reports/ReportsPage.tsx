import { useState } from "react";
import {
  Alert,
  Button,
  Card,
  CardContent,
  Grid,
  MenuItem,
  Stack,
  TextField,
  Typography,
} from "@mui/material";
import DownloadOutlinedIcon from "@mui/icons-material/DownloadOutlined";
import { useGetDepartmentsQuery } from "@/api/departmentApi";
import { downloadCsv } from "@/api/reportsApi";
import { useNotify } from "@/components/feedback/useNotify";
import { CountrySelect, PageHeader } from "@/components/common";
import { getErrorMessage } from "@/utils/format";

type ExportFilters = {
  search: string;
  department: string;
  country: string;
  designation: string;
  employmentStatus: string;
  currency: string;
  minAmount: string;
  maxAmount: string;
  asOf: string;
};

const initialExportFilters: ExportFilters = {
  search: "",
  department: "",
  country: "",
  designation: "",
  employmentStatus: "",
  currency: "",
  minAmount: "",
  maxAmount: "",
  asOf: new Date().toISOString().slice(0, 10),
};

function ReportsPage() {
  const [filters, setFilters] = useState(initialExportFilters);
  const [isExporting, setIsExporting] = useState(false);
  const notify = useNotify();
  const departments = useGetDepartmentsQuery();

  const exportFile = async (type: "employees" | "salaries") => {
    setIsExporting(true);
    try {
      const query =
        type === "employees"
          ? {
              search: filters.search,
              department: filters.department,
              country: filters.country,
              designation: filters.designation,
              employmentStatus: filters.employmentStatus,
            }
          : {
              search: filters.search,
              department: filters.department,
              country: filters.country,
              designation: filters.designation,
              currency: filters.currency,
              minAmount: filters.minAmount,
              maxAmount: filters.maxAmount,
              asOf: filters.asOf,
            };
      await downloadCsv(type, query);
      notify({
        severity: "success",
        message: `${type === "employees" ? "Employee" : "Salary"} CSV export downloaded.`,
      });
    } catch (error) {
      notify({ severity: "error", message: getErrorMessage(error) });
      console.error("CSV export failed", error);
    } finally {
      setIsExporting(false);
    }
  };

  return (
    <Stack spacing={2.5}>
      <PageHeader
        title="Reports & exports"
        description="Download filtered employee and salary data as CSV."
      />
      <Alert severity="info">
        Exports are generated by the server and honor the filters below. Large
        files are streamed without loading the complete dataset in your browser.
      </Alert>
      <Card>
        <CardContent>
          <Typography variant="h6" sx={{ fontWeight: 700, mb: 2 }}>
            Export filters
          </Typography>
          <Grid container spacing={1.5}>
            <Grid size={{ xs: 12, md: 4 }}>
              <TextField
                fullWidth
                size="small"
                label="Search"
                placeholder="Name, employee ID, or email"
                value={filters.search}
                onChange={(event) =>
                  setFilters({ ...filters, search: event.target.value })
                }
              />
            </Grid>
            <Grid size={{ xs: 12, sm: 6, md: 2 }}>
              <TextField
                select
                fullWidth
                size="small"
                label="Department"
                value={filters.department}
                onChange={(event) =>
                  setFilters({ ...filters, department: event.target.value })
                }
              >
                <MenuItem value="">All departments</MenuItem>
                {(departments.data?.data ?? []).map((department) => (
                  <MenuItem key={department.id} value={department.name}>
                    {department.name}
                  </MenuItem>
                ))}
              </TextField>
            </Grid>
            <Grid size={{ xs: 12, sm: 6, md: 2 }}>
              <CountrySelect
                label="Country"
                value={filters.country}
                emptyOption="All countries"
                onChange={(country) => setFilters({ ...filters, country })}
              />
            </Grid>
            <Grid size={{ xs: 12, sm: 6, md: 2 }}>
              <TextField
                fullWidth
                size="small"
                label="Designation"
                value={filters.designation}
                onChange={(event) =>
                  setFilters({ ...filters, designation: event.target.value })
                }
              />
            </Grid>
            <Grid size={{ xs: 12, sm: 6, md: 2 }}>
              <TextField
                select
                fullWidth
                size="small"
                label="Employee status"
                value={filters.employmentStatus}
                onChange={(event) =>
                  setFilters({
                    ...filters,
                    employmentStatus: event.target.value,
                  })
                }
              >
                <MenuItem value="">All statuses</MenuItem>
                <MenuItem value="ACTIVE">Active</MenuItem>
                <MenuItem value="INACTIVE">Inactive</MenuItem>
                <MenuItem value="TERMINATED">Terminated</MenuItem>
              </TextField>
            </Grid>
            <Grid size={{ xs: 12, sm: 6, md: 2 }}>
              <TextField
                fullWidth
                size="small"
                label="Currency"
                value={filters.currency}
                onChange={(event) =>
                  setFilters({
                    ...filters,
                    currency: event.target.value.toUpperCase(),
                  })
                }
                slotProps={{ htmlInput: { maxLength: 3 } }}
              />
            </Grid>
            <Grid size={{ xs: 12, sm: 6, md: 2 }}>
              <TextField
                fullWidth
                size="small"
                label="Min salary"
                value={filters.minAmount}
                onChange={(event) =>
                  setFilters({ ...filters, minAmount: event.target.value })
                }
              />
            </Grid>
            <Grid size={{ xs: 12, sm: 6, md: 2 }}>
              <TextField
                fullWidth
                size="small"
                label="Max salary"
                value={filters.maxAmount}
                onChange={(event) =>
                  setFilters({ ...filters, maxAmount: event.target.value })
                }
              />
            </Grid>
            <Grid size={{ xs: 12, sm: 6, md: 2 }}>
              <TextField
                fullWidth
                size="small"
                label="Salary as of"
                type="date"
                value={filters.asOf}
                onChange={(event) =>
                  setFilters({ ...filters, asOf: event.target.value })
                }
                slotProps={{ inputLabel: { shrink: true } }}
              />
            </Grid>
          </Grid>
          <Stack
            direction={{ xs: "column", sm: "row" }}
            spacing={1.5}
            sx={{ mt: 2.5 }}
          >
            <Button
              variant="contained"
              startIcon={<DownloadOutlinedIcon />}
              onClick={() => void exportFile("employees")}
              disabled={isExporting}
            >
              {isExporting ? "Preparing export…" : "Export employees CSV"}
            </Button>
            <Button
              variant="outlined"
              startIcon={<DownloadOutlinedIcon />}
              onClick={() => void exportFile("salaries")}
              disabled={isExporting}
            >
              {isExporting ? "Preparing export…" : "Export salary CSV"}
            </Button>
          </Stack>
        </CardContent>
      </Card>
    </Stack>
  );
}

export default ReportsPage;